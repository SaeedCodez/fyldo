chk('badge', { Tone: 'Gray', Style: 'Subtle', Size: 'Medium' }, [], H, 24, '4.8 Medium 24');
chk('badge', { Tone: 'Gray', Style: 'Subtle', Size: 'Medium' }, [], PX, [8, 8], '4.8 Medium padding-x 8');
chk('notice', { Tone: 'Gray' }, [], P4, [16, 20, 16, 20], '4.8 padding 20/16');
chk('notice', { Tone: 'Gray' }, [], G, 14, '4.8 gap 14');
