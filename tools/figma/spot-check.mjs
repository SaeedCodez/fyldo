chk('tabs', {}, ['Divider'], H, 1, '4.10 1 px bottom divider');
chk('top-navigation', {}, ['Header'], H, 52, '4.10 row 1 height 52');
chk('top-navigation', {}, ['Header'], PY, [12, 4], '4.10 row 1 padding top 12 / bottom 4');
chk('top-navigation', {}, ['Navigation'], H, 56, '4.10 row 2 height 56');
chk('setting-row', { Layout: 'Inline' }, [], PY, [24, 24], '4.11 padding-y 24');
chk('setting-row', { Layout: 'Inline' }, [], G, 32, '4.11 Inline gap 32');
chk('setting-row', { Layout: 'Stacked' }, [], G, 12, '4.11 Stacked gap 12');
chk('section-card', { Tone: 'Default' }, [], W, 960, '4.11 width 960');
chk('section-card', { Tone: 'Default' }, [], R, 12, '4.11 radius lg');
chk('section-card', { Tone: 'Default' }, ['Header'], G, 6, '4.11 header gap 6');
chk('save-bar', { State: 'Dirty' }, [], W, 960, '4.12 width 960');
chk('save-bar', { State: 'Dirty' }, [], H, 62, '4.12 height 62');
chk('save-bar', { State: 'Dirty' }, [], FX, 'Shadow/Medium', '4.12 Shadow/Medium');
chk('page-header', {}, [], G, 24, '4.12 gap 24');
chk('page-header', {}, ['Title'], TS, 'EN/Heading/32', '4.12 Heading/32');
chk('page-header', {}, ['Text'], G, 6, '4.12 text gap 6');
chk('modal', { Type: 'Default' }, [], W, 560, '4.13 width 560');
chk('modal', { Type: 'Default' }, [], FX, 'Shadow/Large', '4.13 Shadow/Large');
chk('modal', { Type: 'Default' }, ['Footer'], P4, [20, 32, 20, 32], '4.13 footer padding 32/20');
chk('tooltip', { Placement: 'Top' }, ['Bubble'], R, 6, '4.13 bubble radius sm');
chk('tooltip', { Placement: 'Top' }, ['Label'], (n) => n.layout.maxWidth, 240, '4.13 max width 240 (on the Label text)');
chk('tooltip', { Placement: 'Top' }, ['Arrow'], (n) => [n.width, n.height], [10, 5], '4.13 arrow 10x5');
chk('toast', { Tone: 'Neutral' }, [], W, 440, '4.13 width 440');
chk('toast', { Tone: 'Neutral' }, [], G, 12, '4.13 gap 12');
chk('toast', { Tone: 'Neutral' }, [], R, 12, '4.13 radius lg');
chk('empty-state', { Size: 'Large' }, [], W, 560, '4.13 Large width 560');
chk('empty-state', { Size: 'Small' }, [], W, 360, '4.13 Small width 360');
chk('empty-state', { Size: 'Large' }, ['Icon box'], W, 56, '4.13 Large icon box 56');
chk('empty-state', { Size: 'Small' }, ['Icon box'], W, 40, '4.13 Small icon box 40');
chk('empty-state', { Size: 'Large' }, [], G, 20, '4.13 Large gap 20');
for (const r of rows) console.log(`${r.ok ? 'ok  ' : 'DIFF'} ${r.set.padEnd(15)} ${r.variant.padEnd(22)} ${r.layer.padEnd(16)} exp ${JSON.stringify(r.expected)} got ${JSON.stringify(r.actual)}  [${r.ref}]`);
const diffs = rows.filter((r) => !r.ok).length;
console.log(diffs, 'diffs of', rows.length);
process.exitCode = diffs ? 1 : 0;
