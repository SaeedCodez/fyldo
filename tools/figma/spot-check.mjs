/**
 * Spot-checks the exported pack (design/figma/components/*.json) against numbers quoted in docs/design-spec.md §4.
 * Prints one line per check and exits 1 on any difference; it never edits either side. Run: node tools/figma/spot-check.mjs
 */
import { readFileSync } from 'node:fs';
const load = (k) => JSON.parse(readFileSync(`design/figma/components/${k}.json`, 'utf8'));
const find = (n, name) => { if (n.name === name) return n; for (const c of n.children ?? []) { const r = find(c, name); if (r) return r; } };
const path = (n, p) => p.reduce((x, name) => x && find(x, name), n);
const variant = (d, f, set) => d.variants.find((v) => Object.entries(set === 'icon-button' ? f : { Locale: 'EN', ...f }).every(([k, val]) => v.variantProperties[k] === val));
const rows = [];
const chk = (set, f, p, get, expected, ref) => {
  const d = load(set); const v = variant(d, f, set);
  let actual; try { const n = path(v.node, p); actual = n ? get(n, v.node) : 'LAYER NOT FOUND'; } catch (e) { actual = 'ERR ' + e.message; }
  rows.push({ set, variant: Object.values(f).join('/') || '-', layer: p.join('>') || '(root)', expected, actual, ok: JSON.stringify(actual) === JSON.stringify(expected), ref });
};
const H = (n) => n.height, W = (n) => n.width, R = (n) => n.cornerRadius, G = (n) => n.layout?.itemSpacing;
const PX = (n) => [n.layout.paddingLeft, n.layout.paddingRight], PY = (n) => [n.layout.paddingTop, n.layout.paddingBottom];
const P4 = (n) => [n.layout.paddingTop, n.layout.paddingRight, n.layout.paddingBottom, n.layout.paddingLeft];
const FX = (n) => n.effects?.style; const TS = (n) => n.text?.textStyle; const FILL = (n) => n.fills?.[0]?.token; const STROKE = (n) => n.strokes?.paints?.[0]?.token;
const B = { Type: 'Primary', State: 'Default' };
chk('button', { ...B, Size: 'Small' }, [], H, 36, '4.1 Small height 36');
chk('button', { ...B, Size: 'Medium' }, [], H, 44, '4.1 Medium height 44');
chk('button', { ...B, Size: 'Large' }, [], H, 52, '4.1 Large height 52');
chk('button', { ...B, Size: 'Large' }, [], R, 8, '4.1 Large radius md (8)');
chk('button', { ...B, Size: 'Small' }, [], PX, [16, 16], '4.1 Small padding-x 16');
chk('button', { ...B, Size: 'Large' }, ['Label'], TS, 'EN/Button/16', '4.1 Large text Button/16');
chk('button', { ...B, Size: 'Small' }, [], FILL, 'action/primary', '4.1 Primary fill action/primary');
chk('icon-button', { Type: 'Primary', State: 'Default', Size: 'Small' }, [], (n) => [n.width, n.height], [36, 36], '4.1 Icon Button 36 square');
chk('icon-button', { Type: 'Primary', State: 'Default', Size: 'Medium' }, [], (n) => [n.width, n.height], [44, 44], '4.1 Icon Button 44 square');
chk('icon-button', { Type: 'Primary', State: 'Default', Size: 'Large' }, [], R, 8, '4.1 Icon Button Large radius md');
chk('input', { Size: 'Small', State: 'Default' }, [], W, 320, '4.2 width 320');
chk('input', { Size: 'Medium', State: 'Default' }, ['Control'], H, 44, '4.2 Medium control 44');
chk('input', { Size: 'Large', State: 'Default' }, ['Control'], R, 8, '4.2 Large radius md');
chk('input', { Size: 'Small', State: 'Focus' }, ['Control'], FX, 'Focus/Input', '4.2 Focus effect');
chk('input', { Size: 'Small', State: 'Error' }, ['Control'], STROKE, 'status/error/solid', '4.2 Error stroke');
chk('textarea', { State: 'Default' }, ['Control'], H, 120, '4.3 default height 120');
chk('textarea', { State: 'Default' }, ['Control'], P4, [8, 12, 8, 12], '4.3 padding 12/8');
chk('textarea', { State: 'Default' }, [], W, 360, '4.3 width 360');
chk('toggle', { Size: 'Small', Checked: 'False', State: 'Default' }, ['Track'], (n) => [n.width, n.height], [32, 18], '4.4 Small track 32x18');
chk('toggle', { Size: 'Medium', Checked: 'False', State: 'Default' }, ['Track'], (n) => [n.width, n.height], [44, 24], '4.4 Medium track 44x24');
chk('toggle', { Size: 'Medium', Checked: 'False', State: 'Default' }, [], G, 12, '4.4 Medium gap to text 12');
chk('toggle', { Size: 'Small', Checked: 'False', State: 'Default' }, [], G, 8, '4.4 Small gap to text 8');
chk('checkbox', { Checked: 'False', State: 'Default' }, ['Box'], (n) => [n.width, n.height], [20, 20], '4.5 box 20x20');
chk('checkbox', { Checked: 'False', State: 'Default' }, ['Box'], R, 4, '4.5 radius xs');
chk('checkbox', { Checked: 'False', State: 'Default' }, [], G, 8, '4.5 gap 8');
chk('radio', { Checked: 'False', State: 'Default' }, ['Circle'], R, 9999, '4.5 radio full radius');
chk('radio', { Checked: 'True', State: 'Default' }, ['Circle'], (n) => [n.width, n.height], [20, 20], '4.5 circle 20');
chk('radio', { Checked: 'False', State: 'Default' }, ['Control'], H, 20, '4.5 slot 16x20');
chk('select', { Size: 'Small', State: 'Default' }, ['Control'], H, 36, '4.6 Small control 36');
chk('select', { Size: 'Large', State: 'Default' }, ['Control'], H, 52, '4.6 Large control 52');
chk('select', { Size: 'Small', State: 'Default' }, ['Chevron'], (n) => n.icon.size, 16, '4.6 chevron 16');
chk('select-menu', { Type: 'Single' }, [], R, 12, '4.6 radius lg');
chk('select-menu', { Type: 'Single' }, [], P4, [4, 4, 4, 4], '4.6 padding 4');
chk('select-menu', { Type: 'Single' }, [], FX, 'Shadow/Medium', '4.6 Shadow/Medium');
chk('menu-item', { Type: 'Single', State: 'Default' }, [], H, 40, '4.6 height 40');
